#!/usr/bin/env node
/**
 * Regenerates supabase/APPLY_ALL_MIGRATIONS.sql from supabase/migrations/*.sql
 * Run: pnpm supabase:bundle
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = join(root, 'supabase', 'migrations');
const outPath = join(root, 'supabase', 'APPLY_ALL_MIGRATIONS.sql');

const files = (await readdir(migrationsDir))
  .filter((f) => f.endsWith('.sql'))
  .sort();

const parts = [
  `-- Roam: apply all migrations to an EMPTY Supabase database.`,
  `-- Dashboard -> SQL Editor -> New query -> paste entire file -> Run`,
  `-- Regenerated by: pnpm supabase:bundle (${files.length} files)\n`,
];

for (const file of files) {
  const sql = await readFile(join(migrationsDir, file), 'utf8');
  parts.push(`\n-- ========== ${file} ==========\n`);
  parts.push(sql.trimEnd(), '\n');
}

await writeFile(outPath, parts.join(''), 'utf8');
console.log(`Wrote ${outPath} (${files.length} migrations)`);
